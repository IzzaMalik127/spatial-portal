import * as Cesium from 'cesium';
import { fetchAssets, fetchCzml } from '../services/api';
import type { LayerId } from '../types';

export const hasIonToken = Boolean(import.meta.env.VITE_CESIUM_ION_TOKEN);

export type LayerResource =
  | Cesium.ImageryLayer
  | Cesium.Cesium3DTileset
  | Cesium.GeoJsonDataSource
  | Cesium.CzmlDataSource
  | Cesium.TerrainProvider;

/** Adds an imagery layer; satellite is kept at the bottom and WMS on top so blending looks right. */
function addImagery(viewer: Cesium.Viewer, provider: Cesium.ImageryProvider, position?: 'bottom' | 'top') {
  const layer = viewer.imageryLayers.addImageryProvider(provider);
  if (position === 'bottom') viewer.imageryLayers.lowerToBottom(layer);
  if (position === 'top') viewer.imageryLayers.raiseToTop(layer);
  return layer;
}

const requireToken = () => {
  if (!hasIonToken) throw new Error('Add VITE_CESIUM_ION_TOKEN to your .env file to use this layer');
};

/** Creates a layer on the existing viewer (no re-initialisation) and returns a handle for removal. */
export async function addLayer(viewer: Cesium.Viewer, id: LayerId): Promise<LayerResource> {
  switch (id) {
    case 'satellite':
      // True OGC WMTS (REST encoding, Web-Mercator tile matrix set).
      return addImagery(
        viewer,
        new Cesium.WebMapTileServiceImageryProvider({
          url: 'https://services.arcgisonline.com/arcgis/rest/services/World_Imagery/MapServer/WMTS/tile/1.0.0/World_Imagery/{Style}/{TileMatrixSet}/{TileMatrix}/{TileRow}/{TileCol}.jpg',
          layer: 'World_Imagery',
          style: 'default',
          tileMatrixSetID: 'GoogleMapsCompatible',
          tilingScheme: new Cesium.WebMercatorTilingScheme(),
          maximumLevel: 19,
          credit: 'Imagery © Esri, Maxar, Earthstar Geographics',
        }),
        'bottom',
      );
    case 'wms':
      // OGC WMS GetMap requests are generated by Cesium. NASA GIBS: free, no watermark.
      return addImagery(
        viewer,
        new Cesium.WebMapServiceImageryProvider({
          url: 'https://gibs.earthdata.nasa.gov/wms/epsg4326/best/wms.cgi',
          layers: 'BlueMarble_ShadedRelief_Bathymetry',
          parameters: { format: 'image/jpeg' },
          maximumLevel: 8, // the data is ~500 m/pixel, so finer tiles would add nothing
          credit: 'Imagery © NASA GIBS / Blue Marble',
        }),
        'top',
      );
    case 'osm': {
      // Esri World Street Map through Cesium's ArcGIS provider: it reads the service's real maximum zoom
      // and discards Esri's "Map data not yet available" placeholder tiles instead of drawing them.
      const provider = await Cesium.ArcGisMapServerImageryProvider.fromUrl(
        'https://services.arcgisonline.com/ArcGIS/rest/services/World_Street_Map/MapServer',
        { enablePickFeatures: false, credit: 'Map © Esri, HERE, Garmin, © OpenStreetMap contributors' },
      );
      return addImagery(viewer, provider);
    }
    case 'terrain': {
      requireToken();
      const provider = await Cesium.createWorldTerrainAsync();
      viewer.terrainProvider = provider;
      return provider;
    }
    case 'tileset': {
      requireToken();
      const tileset = await Cesium.createOsmBuildingsAsync();
      tileset.maximumScreenSpaceError = 24; // fewer tiles per frame: better FPS
      tileset.dynamicScreenSpaceError = true;
      tileset.style = new Cesium.Cesium3DTileStyle({ color: "color('#d9dde3')" }); // soft light gray, not dark slate
      viewer.scene.primitives.add(tileset);
      return tileset;
    }
    case 'czml': {
      const packets = await fetchCzml(); // typed, cached REST call
      const ds = await Cesium.CzmlDataSource.load(packets);
      await viewer.dataSources.add(ds);
      viewer.clock.shouldAnimate = true; // play the time-dynamic feed
      return ds;
    }
    case 'assets': {
      const data = await fetchAssets(); // typed, cached REST call
      const ds = await Cesium.GeoJsonDataSource.load(data, { clampToGround: false });
      styleAssets(ds);
      await viewer.dataSources.add(ds);
      return ds;
    }
  }
}

/**
 * Like addLayer, but retries a few times on failure (network hiccups while many layers load at once).
 * A missing ion token is not retried, because retrying cannot fix it.
 */
export async function addLayerWithRetry(
  viewer: Cesium.Viewer,
  id: LayerId,
  isWanted: () => boolean = () => true,
  tries = 3,
  delayMs = 1500,
) {
  let lastError: unknown;
  for (let i = 0; i < tries; i++) {
    if (!isWanted() || viewer.isDestroyed()) break; // the user unticked the layer: stop trying
    try {
      return await addLayer(viewer, id);
    } catch (e) {
      lastError = e;
      if (viewer.isDestroyed() || String((e as Error).message).includes('VITE_CESIUM_ION_TOKEN')) break;
      await new Promise((r) => setTimeout(r, delayMs * (i + 1)));
    }
  }
  const msg = lastError instanceof Error ? lastError.message : '';
  throw new Error(msg || 'Could not load this layer (network problem)');
}

export function removeLayer(viewer: Cesium.Viewer, id: LayerId, res: LayerResource) {
  if (viewer.isDestroyed()) return;
  switch (id) {
    case 'satellite':
    case 'osm':
    case 'wms':
      viewer.imageryLayers.remove(res as Cesium.ImageryLayer, true);
      break;
    case 'terrain':
      viewer.terrainProvider = new Cesium.EllipsoidTerrainProvider();
      break;
    case 'tileset':
      viewer.scene.primitives.remove(res);
      break;
    case 'assets':
      viewer.dataSources.remove(res as Cesium.GeoJsonDataSource, true);
      break;
    case 'czml':
      viewer.dataSources.remove(res as Cesium.CzmlDataSource, true);
      viewer.clock.shouldAnimate = false;
      break;
  }
}

const STATUS_COLOR: Record<string, Cesium.Color> = {
  Operational: Cesium.Color.fromCssColorString('#22c55e'),
  'Under Maintenance': Cesium.Color.fromCssColorString('#f59e0b'),
  Planned: Cesium.Color.fromCssColorString('#38bdf8'),
};

const pinCache = new Map<string, HTMLCanvasElement>();

/** Draws a clean teardrop map pin in the given CSS colour (cached per colour). */
function pinImage(cssColor: string): HTMLCanvasElement {
  const hit = pinCache.get(cssColor);
  if (hit) return hit;
  const c = document.createElement('canvas');
  c.width = 48;
  c.height = 64;
  const g = c.getContext('2d')!;
  g.beginPath();
  g.moveTo(24, 62);
  g.bezierCurveTo(24, 62, 4, 38, 4, 22);
  g.arc(24, 22, 20, Math.PI, 0);
  g.bezierCurveTo(44, 38, 24, 62, 24, 62);
  g.closePath();
  g.fillStyle = cssColor;
  g.fill();
  g.lineWidth = 3;
  g.strokeStyle = '#ffffff';
  g.stroke();
  g.beginPath();
  g.arc(24, 22, 8, 0, Math.PI * 2);
  g.fillStyle = '#ffffff';
  g.fill();
  pinCache.set(cssColor, c);
  return c;
}

/** Extrudes building polygons by their `height` property and colours features by status. */
function styleAssets(ds: Cesium.GeoJsonDataSource) {
  const now = Cesium.JulianDate.now();
  for (const e of ds.entities.values) {
    const props = (e.properties?.getValue(now) ?? {}) as Record<string, unknown>;
    const color = STATUS_COLOR[String(props.status)] ?? Cesium.Color.WHITE;
    if (e.polygon) {
      e.polygon.heightReference = new Cesium.ConstantProperty(Cesium.HeightReference.CLAMP_TO_GROUND);
      e.polygon.extrudedHeight = new Cesium.ConstantProperty(Number(props.height) || 20);
      e.polygon.extrudedHeightReference = new Cesium.ConstantProperty(Cesium.HeightReference.RELATIVE_TO_GROUND);
      e.polygon.material = new Cesium.ColorMaterialProperty(color.withAlpha(0.85));
      e.polygon.outline = new Cesium.ConstantProperty(true);
      e.polygon.outlineColor = new Cesium.ConstantProperty(Cesium.Color.BLACK);
    }
    if (e.billboard) {
      const K = Cesium.ConstantProperty;
      e.billboard.image = new K(pinImage(color.toCssColorString()));
      e.billboard.color = new K(Cesium.Color.WHITE); // no tint: keep the pin colours true
      e.billboard.width = new K(32);
      e.billboard.height = new K(43);
      e.billboard.verticalOrigin = new K(Cesium.VerticalOrigin.BOTTOM);
      e.billboard.heightReference = new K(Cesium.HeightReference.CLAMP_TO_GROUND);
      e.billboard.disableDepthTestDistance = new K(5000); // no terrain clipping up close, but hidden behind the globe from afar
      e.billboard.scaleByDistance = new K(new Cesium.NearFarScalar(1.5e3, 1, 2.0e6, 0.4));
      // Name label, only visible when you are reasonably close.
      e.label = new Cesium.LabelGraphics({
        text: String(props.name ?? ''),
        font: '600 13px system-ui, sans-serif',
        style: Cesium.LabelStyle.FILL_AND_OUTLINE,
        fillColor: Cesium.Color.WHITE,
        outlineColor: Cesium.Color.BLACK,
        outlineWidth: 3,
        verticalOrigin: Cesium.VerticalOrigin.TOP,
        pixelOffset: new Cesium.Cartesian2(0, 6),
        heightReference: Cesium.HeightReference.CLAMP_TO_GROUND,
        disableDepthTestDistance: 5000,
        distanceDisplayCondition: new Cesium.DistanceDisplayCondition(0, 8000),
      });
    }
  }
}
